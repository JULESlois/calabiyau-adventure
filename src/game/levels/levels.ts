export interface LevelTheme {
  skyTop: string;
  skyBottom: string;
  far: string;
  mid: string;
  near: string;
  tileBase: string;
  tileEdge: string; // 顶部石雕线脚 / 月光描边
  tileDark: string;
  accent: string; // 主题点缀色(烛火/霓虹/雪光/警灯)
  fog: string; // 雾霭带(含透明度)
  ember: string; // 环境飘浮微粒(余烬/尘埃/落灰)
  ambient: string; // 前景氛围色罩(含透明度)
}

export interface LevelDef {
  id: number;
  name: string;
  subtitle: string;
  song: number;
  theme: LevelTheme;
  rows: string[];
}

function joinSegs(...segs: string[][]): string[] {
  const h = segs[0].length;
  const out: string[] = [];
  for (let r = 0; r < h; r++) {
    let line = '';
    for (const seg of segs) {
      if (seg.length !== h) throw new Error(`segment height mismatch: ${seg.length} vs ${h}`);
      line += seg[r];
    }
    out.push(line);
  }
  return out;
}

